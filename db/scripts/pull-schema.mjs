// Regenerates lib/db/schema.ts + lib/db/relations.ts from the LOCAL database (after npm run db:reset).
//   node db/scripts/pull-schema.mjs   (npm run db:pull)
// drizzle-kit pull also emits pgPolicy(...) entries; they are removed because policies live in the SQL
// migrations only (one source of truth). The schema file is for typed queries, never for migrations.
import { spawnSync } from "node:child_process";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..", "..");
const PULL = join(ROOT, "db", ".pull");
const OUT = join(ROOT, "lib", "db");

const r = spawnSync("npx drizzle-kit pull", { cwd: ROOT, stdio: "inherit", shell: true });
if (r.status !== 0) process.exit(r.status ?? 1);

/** removes every pgPolicy( ... ), call, counting parentheses and skipping template literals */
function stripPolicies(src) {
  let out = "";
  let i = 0;
  let removed = 0;
  while (i < src.length) {
    const at = src.indexOf("pgPolicy(", i);
    if (at < 0) { out += src.slice(i); break; }
    let lineStart = src.lastIndexOf("\n", at) + 1;
    out += src.slice(i, lineStart);
    let j = at + "pgPolicy(".length;
    let depth = 1;
    let inTpl = false;
    while (j < src.length && depth > 0) {
      const ch = src[j];
      if (inTpl) { if (ch === "`") inTpl = false; }
      else if (ch === "`") inTpl = true;
      else if (ch === "(") depth++;
      else if (ch === ")") depth--;
      j++;
    }
    if (src[j] === ",") j++;
    if (src[j] === "\r") j++;
    if (src[j] === "\n") j++;
    i = j;
    removed++;
  }
  return { out, removed };
}

let schema = readFileSync(join(PULL, "schema.ts"), "utf8");
const { out, removed } = stripPolicies(schema);
schema = out
  .replace(/\bpgPolicy, /, "")
  // drizzle-kit reads the column default '{}'::text[] as [""] (an array with one empty string)
  .replace(/\.default\(\[""\]\)/g, ".default(sql`'{}'::text[]`)")
  // drizzle-kit prints the default '' (empty text) as default(')
  .replace(/\.default\('\)/g, ".default('')");
if (/pgPolicy/.test(schema)) throw new Error("pgPolicy left in schema.ts");

const generated = "// GENERATED by db/scripts/pull-schema.mjs from the local database (drizzle-kit pull). Do not edit.\n";
writeFileSync(
  join(OUT, "schema.ts"),
  generated + "// Typed table definitions for queries only; the schema itself is defined by db/migrations/*.sql.\n" + schema,
);
copyFileSync(join(PULL, "relations.ts"), join(OUT, "relations.ts"));
const rel = readFileSync(join(OUT, "relations.ts"), "utf8");
writeFileSync(join(OUT, "relations.ts"), generated + "// Table relations for drizzle's relational queries.\n" + rel);
console.log(`lib/db/schema.ts written (${removed} policy entries removed), lib/db/relations.ts written`);
